"""Analyse the blind 1-5 ratings (PRD D3 / DESIGN §9): join rating_sheet.csv with key.csv
and summarise adequacy / fluency / naturalness per interpreter profile, overall and by
direction, next to chrF on the same rated utterances.

    cd backend && python -m eval.blind_results

Writes docs/benchmarks/blind/results.md and results.csv. Uses the stdlib plus sacrebleu
(already an eval dependency); no network, no API keys.
"""
from __future__ import annotations

import csv
import json
import statistics
from pathlib import Path

import sacrebleu

ROOT = Path(__file__).resolve().parents[2]
BLIND = ROOT / "docs" / "benchmarks" / "blind"
M5 = ROOT / "docs" / "benchmarks" / "results" / "m5"
DIMS = ("adequacy", "fluency", "naturalness")
PROFILES = ("realtime", "cascade-openai", "cascade-haiku", "cascade-elevenlabs")
SCOPES = ("all", "en->es", "es->en")


def load() -> list[dict]:
    key = {r["clip"]: r for r in csv.DictReader(open(BLIND / "key.csv"))}  # noqa: SIM115
    rows = []
    for r in csv.DictReader(open(BLIND / "rating_sheet.csv")):  # noqa: SIM115
        k = key[r["clip"]]
        rows.append({"clip": r["clip"], "profile": k["profile"], "utterance_id": k["utterance_id"],
                     "direction": r["direction"], **{d: int(r[f"{d}_1_5"]) for d in DIMS},
                     "notes": r.get("notes", "")})
    return rows


def stats(xs: list[float]) -> dict:
    return {"n": len(xs), "mean": round(statistics.mean(xs), 2), "median": statistics.median(xs),
            "sd": round(statistics.stdev(xs), 2) if len(xs) > 1 else 0.0, "min": min(xs), "max": max(xs)}


def rated_chrf(profile: str, ids: set[str]) -> dict:
    """Corpus chrF on exactly the rated utterances (same row selection as eval/blind.py)."""
    picked: dict[str, dict] = {}
    for line in open(M5 / "raw" / f"{profile}.jsonl"):  # noqa: SIM115
        r = json.loads(line)
        if r.get("audio_file") and r["id"] in ids and r["id"] not in picked and r.get("status") == "done":
            picked[r["id"]] = r
    out = {}
    for scope in SCOPES:
        rs = [r for r in picked.values() if scope == "all" or (scope == "en->es") == (r["lang"] == "en")]
        out[scope] = round(sacrebleu.corpus_chrf([r.get("target") or "" for r in rs],
                                                 [[r.get("reference", "") for r in rs]]).score, 1)
    return out


def m5_chrf(profile: str) -> float | None:
    for p in json.loads((M5 / "results.json").read_text())["profiles"]:
        if p["profile"] == profile:
            return p["quality"]["all"]["chrF"]
    return None


def analyse(rows: list[dict]) -> list[dict]:
    out = []
    for prof in PROFILES:
        pr = [r for r in rows if r["profile"] == prof]
        chrf = rated_chrf(prof, {r["utterance_id"] for r in pr})
        for scope in SCOPES:
            sr = [r for r in pr if scope == "all" or r["direction"] == scope]
            rec = {"profile": prof, "scope": scope, "n": len(sr), "chrF_rated": chrf[scope]}
            for d in DIMS:
                s = stats([r[d] for r in sr])
                rec.update({f"{d}_{k}": v for k, v in s.items() if k != "n"})
            rec["composite_mean"] = round(statistics.mean(rec[f"{d}_mean"] for d in DIMS), 2)
            out.append(rec)
    return out


def rank(vals: dict[str, float]) -> dict[str, str]:
    """Competition ranking; tied values share a rank, marked with '='."""
    out = {}
    for k, v in vals.items():
        r = 1 + sum(1 for x in vals.values() if x > v)
        tied = sum(1 for x in vals.values() if x == v) > 1
        out[k] = f"{r}=" if tied else str(r)
    return out


def write(res: list[dict], rows: list[dict]) -> None:
    with open(BLIND / "results.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(res[0]))
        w.writeheader()
        w.writerows(res)
    allr = {r["profile"]: r for r in res if r["scope"] == "all"}
    L = ["# Blind rating results (M5)", "",
         ("Generated by `backend/eval/blind_results.py` from `rating_sheet.csv` + `key.csv`. "
          "Machine-readable copy: `results.csv`."), "",
         ("**Caveats.** One rater (Andre). 12 clips per profile (6 per direction), synthetic (TTS-generated) "
          "source audio, 1-5 scale with the source text and a reference translation shown on the sheet. "
          "This is a smoke test, not a statistically meaningful result (DESIGN D3)."), "",
         "## Overall (12 clips per profile)", "",
         ("| Profile | Adequacy mean / median (sd, range) | Fluency mean / median (sd, range) | "
          "Naturalness mean / median (sd, range) | Composite mean | chrF (rated 12) | chrF (all M5) |"),
         "|---|---|---|---|---|---|---|"]

    def cell(r: dict, d: str) -> str:
        return f"{r[d + '_mean']:.2f} / {r[d + '_median']:g} ({r[d + '_sd']:.2f}, {r[d + '_min']}-{r[d + '_max']})"
    for p in PROFILES:
        r = allr[p]
        L.append(f"| {p} | " + " | ".join(cell(r, d) for d in DIMS)
                 + f" | {r['composite_mean']:.2f} | {r['chrF_rated']} | {m5_chrf(p)} |")
    for scope in ("en->es", "es->en"):
        L += ["", f"## {scope} (6 clips per profile)", "",
              "| Profile | Adequacy | Fluency | Naturalness | Composite mean | chrF (rated 6) |", "|---|---|---|---|---|---|"]
        for p in PROFILES:
            r = next(x for x in res if x["profile"] == p and x["scope"] == scope)
            L.append(f"| {p} | " + " | ".join(cell(r, d) for d in DIMS)
                     + f" | {r['composite_mean']:.2f} | {r['chrF_rated']} |")
    comp = {p: allr[p]["composite_mean"] for p in PROFILES}
    ade = {p: allr[p]["adequacy_mean"] for p in PROFILES}
    chrf = {p: allr[p]["chrF_rated"] for p in PROFILES}
    rk = {"composite": rank(comp), "adequacy": rank(ade), "chrF (rated)": rank(chrf)}
    L += ["", "## Rankings (1 = best; = marks a tie)", "",
          "| Profile | " + " | ".join(rk) + " |", "|---|" + "---|" * len(rk)]
    for p in PROFILES:
        L.append(f"| {p} | " + " | ".join(str(rk[k][p]) for k in rk) + " |")
    notes = [r for r in rows if r["notes"].strip()]
    if notes:
        L += ["", "## Rater notes", ""] + [f"- {r['clip']} ({r['profile']}, {r['utterance_id']}): {r['notes']}"
                                            for r in notes]
    low = [r for r in rows if min(r[d] for d in DIMS) <= 3]
    L += ["", "## Clips with any score of 3 or lower", ""]
    L += [f"- {r['clip']} {r['profile']} {r['utterance_id']} ({r['direction']}): "
          f"A{r['adequacy']} F{r['fluency']} N{r['naturalness']}" for r in low] or ["- none"]
    (BLIND / "results.md").write_text("\n".join(L) + "\n")


def main() -> None:
    rows = load()
    res = analyse(rows)
    write(res, rows)
    print((BLIND / "results.md").read_text())


if __name__ == "__main__":
    main()
